import { logger } from '../observability/logger';

export interface GenerateTextOptions {
  prompt: string;
  temperature?: number;
  maxTokens?: number;
}

export interface GenerateTextResult {
  success: boolean;
  text?: string;
  modelUsed?: string;
  promptUsed?: string;
  error?: string;
}

export class NVIDIATextService {
  private getNimConfig(): { apiKey: string; baseUrl: string; chatModel: string } | null {
    const apiKey = process.env.NVIDIA_API_KEY;
    const baseUrl = process.env.NVIDIA_BASE_URL || 'https://integrate.api.nvidia.com/v1';
    const chatModel = process.env.NVIDIA_CHAT_MODEL;
    console.log('NVIDIA config:', { apiKey: !!apiKey, baseUrl: !!baseUrl, chatModel: !!chatModel });
    if (!apiKey || !baseUrl || !chatModel) {
      logger.warn('marketing', 'service', 'getNimConfig', 'NVIDIA configuration incomplete for text generation');
      return null;
    }
    return { apiKey, baseUrl, chatModel };
  }

  /**
   * Generates text using NVIDIA NIM chat/completions endpoint.
   */
  async generateText(options: GenerateTextOptions): Promise<GenerateTextResult> {
    const { prompt, temperature = 0.7, maxTokens = 1000 } = options;

    const nimConfig = this.getNimConfig();
    if (!nimConfig) {
      return {
        success: false,
        error: 'NVIDIA configuration incomplete. Set NVIDIA_API_KEY, NVIDIA_BASE_URL, and NVIDIA_CHAT_MODEL.',
        promptUsed: prompt,
      };
    }

    // Build request body for NVIDIA NIM chat/completions (OpenAI-compatible)
    const body = {
      model: nimConfig.chatModel,
      messages: [{ role: 'user', content: prompt }],
      temperature,
      max_tokens: maxTokens,
      stream: false,
    };

    try {
      const url = nimConfig.baseUrl.endsWith('/v1')
        ? `${nimConfig.baseUrl}/chat/completions`
        : `${nimConfig.baseUrl}/v1/chat/completions`;
      const response = await fetch(url, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${nimConfig.apiKey}`,
        },
        body: JSON.stringify(body),
      });

      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`NVIDIA text generation failed: ${response.status} ${errorText}`);
      }

      const data = await response.json();
      console.log("NVIDIA message:", data.choices[0].message);

      // Expecting OpenAI-like response: { choices: [{ message: { content: 'string' }] } }
      if (!data.choices || data.choices.length === 0) {
        throw new Error('No text generated by NVIDIA');
      }

      const content = data.choices[0].message?.content?.trim() ?? '';
      const reasoning = data.choices[0].message?.reasoning_content?.trim() ?? '';
      const text = content || reasoning;

      logger.info('marketing', 'service', 'generateText', `Generated text with ${nimConfig.chatModel}`, {
        promptLength: prompt.length,
        textLength: text.length,
      });

      return {
        success: true,
        text,
        modelUsed: nimConfig.chatModel,
        promptUsed: prompt,
      };
    } catch (err: any) {
      logger.error('marketing', 'service', 'generateText', 'Error generating text with NVIDIA', { error: err?.message });
      return {
        success: false,
        error: err?.message || 'Unknown error',
        promptUsed: prompt,
      };
    }
  }
}

export const nvidiaTextService = new NVIDIATextService();